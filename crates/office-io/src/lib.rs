//! mdc-office-io — Office 域 XLSX 读路径引擎（xlsx-r1 阶段 B）。
//!
//! workspace 第八成员（双 crate 方案 A：mdc-office 保持纯 std 零三方
//! 依赖的自锁不变量，IO 三方依赖承载于本 crate——分析仓
//! xlsx-r1/REPORT.md §2 架构决策）。三域纪律：对 mdcore 零编译依赖，
//! 与 mdc-office/ mdc-pdf 并列，不建跨格式抽象。
//!
//! ## 读路径门结构（[`io::read_book`]）
//!
//! 1. **门 1 声明值预扫**（[`io::prescan`]）：条目数 / 单条目尺寸 /
//!    声明总量 / 路径逃逸四检查，全部基于 zip 中央目录声明值，零条目
//!    数据读取，敌意输入 typed reject（[`io::ReadError::PrescanRejected`]）；
//! 2. **门 2 尺寸诚实性**（[`io::verify_actual_sizes`]）：逐条目有界
//!    读取计数，实际解压量 > 声明值即拒绝。**策略层补面**：zip 8.6
//!    读界无声明值强制（谎言头条目全量读回零错误，仅 EOF CRC 校验可
//!    被正确 CRC 绕过——lie86 探针 2026-10-13 定谳；zip 9 的内建拒绝
//!    为 9.x 独有），calamine 0.36.1 传递依赖 zip 8.6 → 实际读路径
//!    无此防线，由本层闭环；
//! 3. **calamine 四 API 面**：表名单与顺序 / 值矩阵（含公式缓存值）/
//!    公式文本 / 合并范围。
//!
//! 门在前：敌意输入零解析层接触。错误面三分 = 拒绝（门）/ 容器损坏 /
//! 解析错误（[`io::ReadError`]）。
//!
//! ## Capabilities（能力宣称边界——唯一真源 = 分析仓
//! xlsx-r1/CAPABILITIES.md，本节为引用摘要）
//!
//! - **C1 读取单元格数据：已验证可宣称**（7 维语料 17 件 harness
//!   17/17 零 panic + 50 万格 139ms 量级）。不宣称：样式/关系引用/
//!   图表部件/公式求值/其他容器格式。
//! - **C2 新建 XLSX：已验证（写面产品代码不在本 crate 本轮直移面，
//!   证据 = 分析仓 spike 写读互证 + XML 级样式断言 9/9）**。
//! - **C3 修改已有工作簿：不宣称支持**。已知替代路径「读-改-重建」
//!   的实测保真边界 = 保 表序/值/公式文本/合并；丢 样式/关系引用/
//!   元数据字节保真（五档丢失矩阵定谳）——结构性限制非实现缺陷。
//!
//! ## 容忍度发现（实测钉定，随宣称发布）
//!
//! - 0x00 读侧容忍入值（读侧不过滤——再输出须过 mdc-office
//!   [`mdc_office::sanitize`] 消毒链）；
//! - 垃圾部件静默降级空表（无错误信号——严格模式属后续裁决）；
//! - 缺根闭合 `</worksheet>` 的标签边界外截断被容忍（标签内截断
//!   报错——分界双测钉定）。
//!
